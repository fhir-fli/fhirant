"""Writes test/utils/image_fixtures.dart: real images for the V5.2.6 pixel
limit tests (file_type.dart, maxImagePixels).

Each is a 1x1 image Pillow encodes, and copies of it whose header claims
another size, the way a pixel-flood file is made: the size fields are
rewritten (the PNG IHDR CRC recomputed), the pixel data left as it is.
Pillow then opens every copy and must report the size written, so the
fixtures are checked by a decoder that is not ours.

Run from packages/fhirant_server:
  python3 -I tool/review_2026-10-17/pixel_limit/make_fixtures.py
"""
import base64
import io
import struct
import sys
import zlib

from PIL import Image

Image.MAX_IMAGE_PIXELS = None  # open the flood copies to read their size

LIMIT = 1024 * 1024 * 1024 // 4 // 3  # file_type.dart maxImagePixels
OVER = (9459, 9460)   # 89,482,140 pixels
UNDER = (9459, 9459)  # 89,472,681 pixels
assert OVER[0] * OVER[1] > LIMIT >= UNDER[0] * UNDER[1]


def encode(fmt, **kw):
    out = io.BytesIO()
    Image.new('RGB', (1, 1), (200, 30, 30)).save(out, fmt, **kw)
    return out.getvalue()


def png_sized(b, w, h):
    data = struct.pack('>II', w, h) + b[24:29]
    crc = struct.pack('>I', zlib.crc32(b'IHDR' + data) & 0xFFFFFFFF)
    return b[:16] + data + crc + b[33:]


def gif_sized(b, w, h, screen=True):
    b = bytearray(b)
    if screen:
        b[6:10] = struct.pack('<HH', w, h)
    i = b.index(0x2C, 13)  # first Image Descriptor (no extension before it)
    b[i + 5:i + 9] = struct.pack('<HH', w, h)
    return bytes(b)


def jpeg_sized(b, w, h):
    i = b.index(b'\xff\xc0')
    return b[:i + 5] + struct.pack('>HH', h, w) + b[i + 9:]


png = encode('PNG')
jpeg = encode('JPEG')
gif89 = encode('GIF')
gif87 = bytearray(gif89)
gif87[3:6] = b'87a'
gif87 = bytes(gif87)
# A GIF whose screen is small and whose one frame is a flood.
gif_frame = gif_sized(gif89, *OVER, screen=False)

fixtures = {
    'png1x1': (png, (1, 1)),
    'jpeg1x1': (jpeg, (1, 1)),
    'gif89a1x1': (gif89, (1, 1)),
    'gif87a1x1': (gif87, (1, 1)),
    'pngOver': (png_sized(png, *OVER), OVER),
    'pngUnder': (png_sized(png, *UNDER), UNDER),
    'jpegOver': (jpeg_sized(jpeg, *OVER), OVER),
    'jpegUnder': (jpeg_sized(jpeg, *UNDER), UNDER),
    'gifOver': (gif_sized(gif89, *OVER), OVER),
    'gifUnder': (gif_sized(gif89, *UNDER), UNDER),
    # Pillow sizes such a GIF by the frame, so it reports the flood too.
    'gifFrameOver': (gif_frame, OVER),
}
for name, (b, size) in fixtures.items():
    got = Image.open(io.BytesIO(b)).size
    assert got == size, (name, got, size)
    print(name, len(b), size, flush=True)

lines = [
    '// Generated by tool/review_2026-10-17/pixel_limit/make_fixtures.py;',
    '// do not edit. Real images from Pillow, and copies whose headers claim',
    '// another size (each checked by Pillow), for the V5.2.6 pixel limit.',
    "import 'dart:convert';",
    "import 'dart:typed_data';",
    '',
    'Uint8List _b(String s) => base64.decode(s);',
    '',
]
for name, (b, _) in fixtures.items():
    text = base64.b64encode(b).decode()
    lines.append(f'final Uint8List {name} = _b(')
    lines += [f"  '{text[i:i + 72]}'" for i in range(0, len(text), 72)]
    lines[-1] += ','
    lines.append(');')
open('test/utils/image_fixtures.dart', 'w').write('\n'.join(lines) + '\n')
print('wrote test/utils/image_fixtures.dart', flush=True)

#!/usr/bin/env python3
"""Generates lib/src/utils/common_passwords.g.dart: the common passwords
PasswordPolicy refuses (REVIEW-2026-10-17 finding 18).

OWASP ASVS 5.0.0 V6.2.4 (L1): "passwords submitted during account
registration or password change are checked against an available set of,
at least, the top 3000 passwords which match the application's password
policy, e.g. minimum length." The policy is 12 to 128 characters, so the
set is every entry of that length in the two lists below, lowercased (the
check ignores case). Both lists are from SecLists (Daniel Miessler, MIT
License); the license text is copied into the generated file, as it asks.

Run from packages/fhirant_server, with the two lists downloaded beside each
other in <dir>:
  python3 -I tool/generate_common_passwords.py <dir>
The script refuses to write if a list's SHA-256 is not the one recorded
here, so the generated file always says what it was built from.
"""
import hashlib
import os
import sys

BASE = ('https://raw.githubusercontent.com/danielmiessler/SecLists/master/'
        'Passwords/Common-Credentials/')
SOURCES = {
    # UK National Cyber Security Centre's 100,000 most used passwords
    # (from Have I Been Pwned).
    '100k-most-used-passwords-NCSC.txt':
        'c2e5696882c603b7',
    # The top 1,000,000 of the Pwdb breach compilation, by frequency.
    'Pwdb_top-1000000.txt':
        'e9a88f67aafe6549',
}
MIN, MAX = 12, 128
# The 20 the policy listed by hand before; kept.
EARLIER = [
    'password1234', 'password12345', 'password123456', 'passwordpassword',
    'qwertyuiop12', 'qwerty123456', '123456789012', '1234567890123',
    'iloveyou1234', 'changeme1234', 'letmein12345', 'welcome12345',
    'admin1234567', 'trustno12345', 'monkey1234567', 'dragon1234567',
    'master1234567', 'abc123456789', 'passw0rd1234', 'aaaaaaaaaaaa',
]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lib',
                   'src', 'utils', 'common_passwords.g.dart')


def dart_string(s):
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == "'":
            out.append("\\'")
        elif ch == '$':
            out.append('\\$')
        elif ord(ch) < 0x20 or ord(ch) == 0x7f:
            out.append('\\u{%x}' % ord(ch))
        else:
            out.append(ch)
    return "'" + ''.join(out) + "'"


def main():
    folder = sys.argv[1]
    seen = set()
    words = []
    counts = {}
    digests = {}
    for name, expected in SOURCES.items():
        data = open(os.path.join(folder, name), 'rb').read()
        digest = hashlib.sha256(data).hexdigest()
        if not digest.startswith(expected):
            sys.exit('%s: sha256 %s, expected %s...' % (name, digest, expected))
        digests[name] = digest
        n = 0
        for line in data.decode('utf-8', 'replace').splitlines():
            word = line.strip('\r\n').lower()
            if MIN <= len(word) <= MAX and word not in seen:
                seen.add(word)
                words.append(word)
                n += 1
        counts[name] = n
    earlier_new = 0
    for word in EARLIER:
        if word not in seen:
            seen.add(word)
            words.append(word)
            earlier_new += 1
    license_text = open(os.path.join(folder, 'LICENSE')).read().strip()
    with open(OUT, 'w') as f:
        f.write('// GENERATED by tool/generate_common_passwords.py. Do not edit.\n')
        f.write('//\n')
        for name in SOURCES:
            f.write('// %s%s\n//   sha256 %s, %d new entries of %d-%d chars\n'
                    % (BASE, name, digests[name], counts[name], MIN, MAX))
        f.write('// plus %d of the %d entries the policy listed by hand before '
                '(the rest are in the lists).\n' % (earlier_new, len(EARLIER)))
        f.write('// %d entries in all, lowercased.\n//\n' % len(words))
        f.write('// The lists are from SecLists, under this license:\n//\n')
        for line in license_text.splitlines():
            f.write(('// ' + line).rstrip() + '\n')
        f.write('\n// Generated: escaped as written, never groomed.\n'
                '// ignore_for_file: lines_longer_than_80_chars, use_raw_strings, '
                'avoid_escaping_inner_quotes\n\n')
        f.write('/// Common passwords of 12-128 characters, lowercased.\n')
        f.write('const List<String> commonPasswordList = [\n')
        for word in words:
            f.write('  %s,\n' % dart_string(word))
        f.write('];\n')
    print('wrote %d entries -> %s' % (len(words), OUT), flush=True)


if __name__ == '__main__':
    main()
